"""Generates firmware/src/lpg_tables.h: the ADSR's times and the low pass gate's filter coefficients.
  python3 tools/gen_lpg_tables.py > firmware/src/lpg_tables.h

  ENV_FRAMES[v]   v = 0..127: the knob's time in frames, 0.5 ms .. 10 s, exponential
  ENV_COEF[v]     the one-pole coefficient that falls to 1/e in that time (Q24): decay and release
  LPG_G[i]        i = 0..255 the gate's control: tan(pi fc / FS), fc 25 Hz .. 15 kHz exponential (Q24)
  LPG_K[v]        v = 0..127 RING: the filter's damping k = 1/Q, 2 (no ring) .. 0.025 (Q 40) (Q24)
  LPG_COMP[v]     the level the resonance adds, taken back out (Q12): measured on the circuit's output"""
import math

FS = 44100
T0, T1 = 0.0005, 10.0
F0, F1 = 25.0, 15000.0
K0, K1 = 2.0, 0.025


def frames(v):
    return max(1, round(T0 * (T1 / T0) ** (v / 127) * FS))


def k_of(v):
    return K0 * (K1 / K0) ** ((v / 127) ** 0.7)    # most of the knob's travel where the ring is audible


def comp(v):
    # the ring adds little to the level of the circuit's broadband output, a little more to a pinged gate: measured
    # on the circuit (tests/basis_test.c probes: RMS against RING), q^-0.08 keeps it within ~1 dB
    q = 1 / k_of(v)
    return (max(q, 0.5) / 0.5) ** -0.08


def row(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    print("/* generated by tools/gen_lpg_tables.py: do not edit */")
    print(row("ENV_FRAMES", "uint32_t", [frames(v) for v in range(128)]))
    print(row("ENV_COEF", "uint32_t", [round((1 - math.exp(-1 / frames(v))) * (1 << 24)) for v in range(128)]))
    print(row("LPG_G", "uint32_t",
              [round(math.tan(math.pi * F0 * (F1 / F0) ** (i / 255) / FS) * (1 << 24)) for i in range(256)]))
    print(row("LPG_K", "uint32_t", [round(k_of(v) * (1 << 24)) for v in range(128)]))
    print(row("LPG_COMP", "uint16_t", [round(comp(v) * 4096) for v in range(128)]))


if __name__ == "__main__":
    main()
